#!/usr/bin/env python3
"""Build law/bands.js: the four valence cut points that split the five modes into ranked bands.

Why: with five *even* bands (0.2, 0.4, 0.6, 0.8) the stored feeling, once smoothed verse to verse,
almost never falls below 0.2, so Aeolian sounded on 0.4% of the Bible and lament (Lamentations,
Psalm 88, Job 3) played mostly in Dorian and Mixolydian. Ranked bands, like the seasons strip
(variant B), cut at the 20th/40th/60th/80th percentile of the feeling as it is really heard, so
each mode carries about a fifth of Scripture and the darkest fifth is truly minor.

The feeling is taken exactly as law/chapter.js hears it: per chapter, from verse 1, smoothed
Ebar = 0.5*E + 0.5*Ebar_prev, only verses the BSB sings (empty slots skipped).
Usage: python3 -I tools/build_bands.py   (writes law/bands.js; deterministic)
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
canon = json.load(open(os.path.join(ROOT, 'data/canon.json')))
vals = []
for entry in canon:
    f = entry[1]
    bsb = json.load(open(os.path.join(ROOT, 'data/bsb', f)))
    vad = json.load(open(os.path.join(ROOT, 'data/vad', f)))
    for ci, verses in enumerate(bsb['c']):
        s, prev = vad[ci] if ci < len(vad) else '', None
        for vi, text in enumerate(verses):
            if not (text and text.strip()):
                continue
            x = s[vi * 6: vi * 6 + 2]
            v = int(x) / 99 if len(x) == 2 else 0.5
            prev = v if prev is None else 0.5 * v + 0.5 * prev
            vals.append(prev)
vals.sort()
n = len(vals)
# Cut q sits halfway between the last verse below the quantile and the first at or above it.
cuts = [round((vals[int(q * n) - 1] + vals[int(q * n)]) / 2, 6) for q in (0.2, 0.4, 0.6, 0.8)]
out = f"""// GENERATED by tools/build_bands.py from data/vad and data/bsb. Do not edit by hand.
// Valence cut points between the five modes, ranked: the 20th, 40th, 60th and 80th percentile
// of the smoothed verse feeling across all {n} sung verses, so each mode carries about a fifth.
export const BANDS = {json.dumps(cuts)};
export const BANDS_VERSES = {n};
"""
open(os.path.join(ROOT, 'law/bands.js'), 'w').write(out)
print('verses', n, 'cuts', cuts)
